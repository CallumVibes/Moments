#!/usr/bin/env node
/* Build: assemble index.html from src/ modules, then pin the CSP script hashes.
 *
 * The deployment story in the README does not change — the output is still one
 * self-contained index.html you can drop on any static host. What changes is
 * that it is no longer the thing you edit by hand.
 *
 * The CSP pins a sha256 of the inline bundle, so every source edit invalidates
 * it. Recomputing that by hand is a footgun: get it wrong and the app loads a
 * blank page with one console error. This script is the only supported way to
 * produce index.html.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { minify } from 'terser';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const INCLUDE = /^([ \t]*)\/\/\s*@include\s+(\S+)\s*$/gm;

async function expand(src, seen = []) {
  const matches = [...src.matchAll(INCLUDE)];
  if (!matches.length) return src;
  let out = '';
  let last = 0;
  for (const m of matches) {
    const [full, indent, rel] = m;
    if (seen.includes(rel)) throw new Error(`circular @include: ${[...seen, rel].join(' -> ')}`);
    const body = await expand(await readFile(join(root, rel), 'utf8'), [...seen, rel]);
    out += src.slice(last, m.index)
         + `${indent}/* ==== ${rel} ==== */\n`
         + body.replace(/\n$/, '').split('\n').map(l => (l ? indent + l : l)).join('\n');
    last = m.index + full.length;
  }
  return out + src.slice(last);
}

let html = await expand(await readFile(join(root, 'src/index.html'), 'utf8'));

/* The OPRF server needs the same curve arithmetic as the client. Extracted
 * BEFORE minification, because the markers it looks for do not survive it —
 * and the server has no reason to run minified code anyway. Extracting it
 * from the very bundle the browser runs, rather than adding an npm dependency,
 * means the two can never drift onto different implementations — and keeps the
 * server dependency-free. */
const vendorStart = html.indexOf('(()=>{var fn=Object.defineProperty');
const vendorEnd = html.indexOf('})();', html.indexOf('window.MomentsCrypto='));
if (vendorStart < 0 || vendorEnd < 0) throw new Error('could not locate the vendored curve bundle');
const vendor = html.slice(vendorStart, vendorEnd + 5);
await writeFile(join(root, 'server/vendor-secp256k1.mjs'),
  `/* GENERATED by scripts/build.mjs — do not edit.\n`
+ ` * The @noble/curves bundle the browser runs, re-exported for the OPRF server\n`
+ ` * so both sides share one implementation. Regenerate with \`npm run build\`.\n`
+ ` */\nconst window = {};\n${vendor}\nexport const { secp256k1 } = window.MomentsCrypto;\n`);
console.log('wrote server/vendor-secp256k1.mjs');

/* Minify the inline scripts unless --no-minify.
 *
 * This matters more than the download: nothing on the page paints until the
 * bundle has been parsed and compiled, and on a mid-range phone that is the
 * single largest cost in starting the app. Halving the bytes roughly halves
 * that work.
 *
 * Names are mangled but NOT top-level ones: the app wires buttons through a
 * `data-act` map and the test suites drive real functions by name, so renaming
 * globals would break both silently. Comments go; the source keeps them. */
if (!process.argv.includes('--no-minify')) {
  const before = html.length;
  const blocks = [...html.matchAll(/(<script(?![^>]*\bsrc=)[^>]*>)([\s\S]*?)(<\/script>)/g)];
  for (const [full, open, code, close] of blocks) {
    if (code.trim().length < 400) continue;              // tiny bootstraps: leave alone
    const out = await minify(code, {
      ecma: 2020,
      compress: { passes: 2, drop_debugger: true },
      mangle: { toplevel: false },                       // see note above
      format: { comments: false },
    });
    if (out.error) throw out.error;
    if (!out.code) throw new Error('terser returned empty output');
    html = html.replace(full, () => open + out.code + close);
  }
  console.log(`minified: ${(before / 1024).toFixed(0)} KB -> ${(html.length / 1024).toFixed(0)} KB`);
}

// Hash every inline <script> (ones with src= are not covered by a hash).
const scripts = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(m => m[1]);
if (!scripts.length) throw new Error('no inline scripts found — refusing to write a CSP that allows nothing');
const hashes = scripts.map(s => `'sha256-${createHash('sha256').update(s, 'utf8').digest('base64')}'`);

const cspRe = /script-src ([^;]*);/;
if (!cspRe.test(html)) throw new Error('no script-src directive found in the CSP');
const built = html.replace(cspRe, `script-src ${hashes.join(' ')};`);

await writeFile(join(root, 'index.html'), built);


console.log(`built index.html  (${(built.length / 1024).toFixed(0)} KB, ${scripts.length} inline script(s) pinned)`);
for (const h of hashes) console.log('  ' + h);
